for (const word of WORDS) {
  const key = word.id.toLowerCase();
  if (!WORD_BY_ID[key]) WORD_BY_ID[key] = word;
}

export function word(id: string): Word {
  const found = WORD_BY_ID[id.toLowerCase()];
  if (!found) throw new Error(`Word "${id}" is not in the word bank`);
  return found;
}

/** True when every spelling unit in the word uses a taught correspondence. */
export function isDecodable(wd: Word, taught: Set<string>): boolean {
  return wd.tokens.every((t) => t.c === "_" || (t.c !== "*" && taught.has(t.c)));
}

/** Phoneme ids of a word, in order (silent letters skipped). */
export function phonemesOf(wd: Word): string[] {
  return wd.tokens.filter((t) => t.c !== "_" && t.c !== "*").map((t) => CORR_BY_ID[t.c].phoneme);
}

/** True when the word contains a "same letters, two sounds" pair (consonant blend). */
export function hasAdjacentConsonants(wd: Word): boolean {
  const kinds = wd.tokens
    .filter((t) => t.c !== "_" && t.c !== "*")
    .map((t) => PHONEME_BY_ID[CORR_BY_ID[t.c].phoneme].kind);
  return kinds.some((k, i) => i > 0 && k === "consonant" && kinds[i - 1] === "consonant");
}

/** Plain consonant-vowel-consonant word using single sounds. */
export function isCVC(wd: Word): boolean {
  const ph = phonemesOf(wd).map((p) => PHONEME_BY_ID[p].kind);
  return ph.length === 3 && ph[0] === "consonant" && ph[1] === "vowel" && ph[2] === "consonant" && wd.text === wd.text.toLowerCase();
}
