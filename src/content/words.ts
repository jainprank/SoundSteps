import type { Token, Word } from "./types";
import { CORR_BY_ID } from "./correspondences";
import { PHONEME_BY_ID } from "./phonemes";

// The word bank. Each word is written as its spelling units separated by spaces:
//   "sh i p"            → sh + i + p
//   "c a=a_e k e=_"     → the a uses the a-e split digraph; the final e is silent
//   "a pp le=*"         → "*" marks a part not taught as a correspondence; such words
//                         are only used for listening/pictures, never for reading.
// A word is offered for reading only once every correspondence in it has been taught
// (see `isDecodable`), which keeps every reading task fair.

function parse(spec: string): Token[] {
  return spec.split(" ").map((part) => {
    const [g, c] = part.split("=");
    return { g, c: c ?? g.toLowerCase() };
  });
}

function w(spec: string, emoji?: string, extra: { meaning?: string; syllables?: number } = {}): Word {
  const tokens = parse(spec);
  const text = tokens.map((t) => t.g).join("");
  const vowels = tokens.filter((t) => {
    const corr = CORR_BY_ID[t.c];
    return corr && PHONEME_BY_ID[corr.phoneme]?.kind === "vowel";
  }).length;
  return { id: text, text, tokens, emoji, syllables: extra.syllables ?? Math.max(1, vowels), meaning: extra.meaning };
}

